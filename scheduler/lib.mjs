// Pure helpers for the scheduler. No I/O, no dependencies.
export const SAFE_KINDS = ['fetch_digest', 'stale_check', 'heartbeat'];
const ID_RE = /^[a-z0-9][a-z0-9-]{0,62}$/;
const DAYS = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];

export function validateJob(j) {
  const errors = [];
  if (!j || typeof j !== 'object' || Array.isArray(j)) return { ok: false, errors: ['job must be an object'] };
  if (typeof j.id !== 'string' || !ID_RE.test(j.id)) errors.push('id must match ' + ID_RE);
  if (typeof j.schedule !== 'string' || !parseSchedule(j.schedule)) errors.push('schedule must be hourly | daily[@HH] | weekly@<day>[@HH]');
  if (!SAFE_KINDS.includes(j.kind)) errors.push('kind must be one of ' + SAFE_KINDS.join(', '));
  if (typeof j.requiresApproval !== 'boolean') errors.push('requiresApproval must be boolean');
  if (typeof j.enabled !== 'boolean') errors.push('enabled must be boolean');
  const p = j.params;
  if (p === null || typeof p !== 'object' || Array.isArray(p)) errors.push('params must be an object');
  else if (j.kind === 'fetch_digest') {
    const urls = p.urls ?? [], queries = p.queries ?? [];
    if (!Array.isArray(urls) || !Array.isArray(queries)) errors.push('params.urls and params.queries must be arrays');
    else {
      if (!urls.length && !queries.length) errors.push('fetch_digest needs params.urls or params.queries');
      if (urls.length + queries.length > 10) errors.push('at most 10 urls+queries');
      if (!urls.every((u) => typeof u === 'string' && /^https:\/\//i.test(u))) errors.push('urls must be https strings');
      if (!queries.every((q) => typeof q === 'string' && q.trim() && q.length <= 300)) errors.push('queries must be non-empty strings (<=300 chars)');
    }
  } else if (j.kind === 'stale_check') {
    if (!isSafeRelPath(p.file)) errors.push('params.file must be a relative path inside the repo');
    if (!(Number.isFinite(p.days) && p.days > 0)) errors.push('params.days must be a positive number');
  } else if (j.kind === 'heartbeat') {
    if (p.message !== undefined && typeof p.message !== 'string') errors.push('params.message must be a string');
  }
  return { ok: errors.length === 0, errors };
}

export function isSafeRelPath(f) {
  return typeof f === 'string' && f.length > 0 && !f.startsWith('/') && !/^[a-z]:/i.test(f) && !f.includes('\\') && !f.split('/').includes('..') && !f.includes('\0');
}

// "hourly" | "daily" | "daily@07" | "weekly@mon" | "weekly@mon@07"  (UTC; default hour 06)
export function parseSchedule(s) {
  if (typeof s !== 'string') return null;
  const m = s.trim().toLowerCase().split('@');
  const hr = (x) => (x === undefined ? 6 : /^\d{1,2}$/.test(x) && +x < 24 ? +x : null);
  if (m[0] === 'hourly' && m.length === 1) return { every: 'hourly' };
  if (m[0] === 'daily' && m.length <= 2) { const h = hr(m[1]); return h === null ? null : { every: 'daily', hour: h }; }
  if (m[0] === 'weekly' && m.length >= 2 && m.length <= 3) {
    const d = DAYS.indexOf(m[1]); const h = hr(m[2]);
    return d < 0 || h === null ? null : { every: 'weekly', day: d, hour: h };
  }
  return null;
}

// Runner is expected to fire at least hourly; a job is due in the UTC hour it targets.
export function isDue(schedule, now = new Date()) {
  const s = parseSchedule(schedule);
  if (!s) return false;
  if (s.every === 'hourly') return true;
  if (now.getUTCHours() !== s.hour) return false;
  return s.every === 'daily' || now.getUTCDay() === s.day;
}

export const dateStamp = (d) => d.toISOString().slice(0, 10);
export const minuteStamp = (d) => d.toISOString().slice(0, 16).replace(/[-:T]/g, '');

const clip = (s, n) => { s = String(s ?? '').replace(/\s+/g, ' ').trim(); return s.length > n ? s.slice(0, n - 1) + '…' : s; };

// sections: [{ heading, url?, items: [{title,url,snippet}], note?, error? }]
export function renderDigest({ id, title, date, sections }) {
  const out = [`# ${title || id} (${date})`, ''];
  for (const s of sections) {
    out.push(`## ${clip(s.heading, 200)}`, '');
    if (s.error) out.push(`_Failed: ${clip(s.error, 200)}_`, '');
    else if (s.note) out.push(clip(s.note, 1500), '');
    if (s.items?.length) {
      for (const it of s.items) out.push(`- [${clip(it.title || it.url, 150)}](${it.url})${it.snippet ? ' - ' + clip(it.snippet, 280) : ''}`);
      out.push('');
    }
  }
  out.push('---', `Generated by scheduler job \`${id}\`. Read-only; nothing was sent or published.`, '');
  return out.join('\n');
}

export function findStale(items, { days, dateField = 'updated', labelField = 'name' }, now = new Date()) {
  const cutoff = now.getTime() - days * 86400000;
  const stale = [], undated = [];
  for (const it of Array.isArray(items) ? items : []) {
    const label = String(it?.[labelField] ?? it?.title ?? it?.id ?? '(unnamed)');
    const t = Date.parse(it?.[dateField]);
    if (Number.isNaN(t)) undated.push(label);
    else if (t < cutoff) stale.push({ label, date: new Date(t).toISOString().slice(0, 10), ageDays: Math.floor((now.getTime() - t) / 86400000) });
  }
  stale.sort((a, b) => b.ageDays - a.ageDays);
  return { stale, undated };
}

export function renderStale({ id, date, days, total, stale, undated }) {
  const out = [`# Stale items: ${id} (${date})`, '', `${stale.length} of ${total} items older than ${days} days.`, ''];
  for (const s of stale) out.push(`- ${s.label} - last updated ${s.date} (${s.ageDays} days)`);
  if (undated.length) out.push('', `Items without a valid date (${undated.length}): ${undated.map((x) => clip(x, 60)).join(', ')}`);
  out.push('', '---', `Generated by scheduler job \`${id}\`.`, '');
  return out.join('\n');
}

export function renderSummary(rows, { dry, date }) {
  const out = [`## Scheduled jobs ${dry ? '(dry run) ' : ''}- ${date}`, '', '| Job | Kind | Status | Detail |', '|---|---|---|---|'];
  for (const r of rows) out.push(`| ${r.id} | ${r.kind || '-'} | ${r.status} | ${String(r.detail ?? '').replace(/[|\n\r]/g, ' ').slice(0, 200)} |`);
  if (!rows.length) out.push('| (none) | | | no jobs due |');
  return out.join('\n') + '\n';
}
